//Arithmetic operators

//Addition
console.log(10+5);

//Subtraction
console.log(12-6);

//multiplication
console.log(15*2);

//division
console.log(10/2);

//modulos
console.log(10%3); //remainder = 1


//Assignment operator --> += , -= , *= , /= , %=
a=10
console.log(a+=5);//a=a+5=>10+5=15

console.log(a-=10);//a=a-10=>15-10=5

console.log(a*=2);//a=a*2=>5*2=10

console.log(a/=4);//a=a/4=>10/4=2.5

//comparision operators

 //loose equality(==) => compares only the value
 //coercion=>type conversion

 console.log(2=='2') //true
console.log(2==true)//false 
console.log(1==false)//false
console.log(null==undefined)//true
 

//strict equality(===) => compares both the value and datatype
console.log(2==='2') //false
console.log(null===undefined) //false
 
console.log(5<2)//false

 //logical operators

 //&& (and)
console.log(true && true);//true
console.log(true && false);//false

//  //|| (or)
console.log(true || false);//true

//  //!(not)-> inverse of input
console.log(!true);//false
console.log(!false);//true


 //unary opertors-> works on single operand

 //increment-> increments the value by 1

 //pre increment(++x)

x=5
console.log(++x) //6
console.log(x); //6

 //post increment(x++)

 console.log(x++)//6
 console.log(x)//7
 

 //decrement-> decrement the value by 1
 
 //pre decrement(--y)
y=2
console.log(--y)//1
console.log(y)//1

//post decrement(y--)
console.log(y--)//1
console.log(y)//0










